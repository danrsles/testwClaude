-- Who follows whom. A user's wants list shows their own wants and those of
-- everyone they follow (see WantRepository.findFeed).
CREATE TABLE follows (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    followee_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Following twice is a no-op: FollowRepository.followIfAbsent relies on
    -- this constraint for its ON CONFLICT DO NOTHING.
    CONSTRAINT follows_pair_unique UNIQUE (follower_id, followee_id),
    CONSTRAINT follows_not_self CHECK (follower_id <> followee_id)
);
