-- Circles: groups, like a group chat (see docs/design/wants-signups-and-notifications.md,
-- step 8c). One owner, who adds and removes members; members see the circle and
-- each other. Wants don't use circles until step 8d.
--
-- Deleting a circle archives it (archived_at) rather than removing the row,
-- because wants will point at it. owner_id has no ON DELETE action, like
-- wants.user_id: a user who owns circles can't be deleted without its own design.
CREATE TABLE circles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT      NOT NULL REFERENCES users (id),
    name        VARCHAR(40) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    archived_at TIMESTAMPTZ,
    -- What circle_members' key to (circle_id, owner_id) points at.
    CONSTRAINT circles_id_owner_unique UNIQUE (id, owner_id),
    CONSTRAINT circles_name_not_blank CHECK (btrim(name) <> '')
);

-- Names are unique per owner, ignoring case, among circles not deleted, so a
-- deleted circle's name can be used again. CircleService checks first under the
-- owner's row lock; this is the backstop.
CREATE UNIQUE INDEX circles_live_name_unique ON circles (owner_id, lower(name)) WHERE archived_at IS NULL;

-- One row per member. The owner is not a row here: they can't follow themselves.
CREATE TABLE circle_members (
    circle_id  BIGINT      NOT NULL,
    owner_id   BIGINT      NOT NULL,
    member_id  BIGINT      NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (circle_id, member_id),
    CONSTRAINT circle_members_circle_fk FOREIGN KEY (circle_id, owner_id) REFERENCES circles (id, owner_id),
    -- Only the owner's followers can be members, and unfollowing the owner
    -- removes you from all their circles: deleting the follow cascades here.
    CONSTRAINT circle_members_follow_fk FOREIGN KEY (member_id, owner_id)
        REFERENCES follows (follower_id, followee_id) ON DELETE CASCADE
);

-- "Circles I'm in", and in 8d, who can see a circle's want.
CREATE INDEX circle_members_member_idx ON circle_members (member_id);

-- Being added tells you (CIRCLE_ADDED). The notification keeps the circle's
-- name as it was, like want_message.
ALTER TABLE notifications
    ADD COLUMN circle_id   BIGINT REFERENCES circles (id),
    ADD COLUMN circle_name VARCHAR(40);

ALTER TABLE notifications DROP CONSTRAINT notifications_type_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_type_check
    CHECK (type IN ('FOLLOW', 'WANT_CREATED', 'WANT_SIGNUP', 'WANT_WITHDRAWN', 'WANT_UPDATED',
                    'WANT_CLOSED', 'WANT_REOPENED', 'WANT_CANCELLED', 'WANT_STARTED', 'WANT_ENDED',
                    'WANT_OPEN_INVITE', 'WANT_LIMITED', 'WANT_DEADLINE_CHANGED', 'WANT_EXPIRED',
                    'WANT_POSTED', 'CIRCLE_ADDED'));
