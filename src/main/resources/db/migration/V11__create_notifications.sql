-- The letterbox: everything a user should hear about, written whether or not
-- they are signed in, and read by GET /notifications when they next look.
-- One table for every kind of event; new kinds widen the type check (see
-- docs/design/wants-signups-and-notifications.md).
CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    actor_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type         VARCHAR(32) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Null until the recipient has seen it.
    read_at      TIMESTAMPTZ,
    CONSTRAINT notifications_type_check CHECK (type IN ('FOLLOW'))
);

-- Every read is "this recipient's newest", and the badge counts their unread.
CREATE INDEX notifications_recipient_idx ON notifications (recipient_id, id DESC);
