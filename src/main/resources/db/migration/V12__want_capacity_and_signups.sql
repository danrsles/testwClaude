-- Signups: a want takes up to `capacity` people, its owner included, first
-- come, first served (see docs/design/wants-signups-and-notifications.md).
ALTER TABLE wants
    ADD COLUMN capacity INT NOT NULL DEFAULT 1,
    ADD CONSTRAINT wants_capacity_check CHECK (capacity >= 1);

-- The lineup. Seats taken are counted from these rows, never kept in a
-- counter on wants, so the two cannot drift apart.
CREATE TABLE want_signups (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    want_id    BIGINT      NOT NULL REFERENCES wants (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Signing up twice is a no-op: WantSignupRepository.signUpIfAbsent relies
    -- on this constraint for its ON CONFLICT DO NOTHING.
    CONSTRAINT want_signups_pair_unique UNIQUE (want_id, user_id)
);

-- Every existing want's owner holds its one seat, as creating a want now does.
INSERT INTO want_signups (want_id, user_id)
SELECT id, user_id FROM wants;

-- Notifications about a want point at it, and copy its message so they still
-- read correctly after it is edited. An edit's notification also keeps the
-- name it replaced, null when only the category changed.
ALTER TABLE notifications
    ADD COLUMN want_id          BIGINT REFERENCES wants (id) ON DELETE CASCADE,
    ADD COLUMN want_message     VARCHAR(255),
    ADD COLUMN previous_message VARCHAR(255);

ALTER TABLE notifications DROP CONSTRAINT notifications_type_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_type_check
    CHECK (type IN ('FOLLOW', 'WANT_CREATED', 'WANT_SIGNUP', 'WANT_WITHDRAWN', 'WANT_UPDATED'));
